export const calculateLegacyScore = (player) => {
  const { achievements, runnerUp, poolOuts } = player

  return (
    achievements.trophies * 100 +
    achievements.medals * 50 +
    achievements.gold * 40 +
    achievements.silver * 25 +
    achievements.bronze * 15 +
    runnerUp.captain * 30 +
    runnerUp.player * 10 -
    poolOuts * 5
  )
}


export const getLegendsLeaderboard = () => {
  return [...legendsData]
    .map((player) => ({
      ...player,
      legacyScore: calculateLegacyScore(player),
    }))
    .sort((a, b) => b.legacyScore - a.legacyScore)
}